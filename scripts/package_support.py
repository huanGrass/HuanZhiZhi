"""Validation for portable releases and source-only skill updates."""
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess

FORMAT = "portable-python-v1"
DEFAULT_TASKS = ()

# The public runtime supports Widgets and SVG, not the complete Qt SDK.
# Keep these rules identical for copying and update compatibility fingerprints.
QT_MODULES = {"Core", "Gui", "Widgets", "Svg", "SvgWidgets", "Network",
              "OpenGL", "OpenGLWidgets", "PrintSupport", "Test"}


def task_ignore(directory, names):
    ignored = set(shutil.ignore_patterns("tests", "__pycache__", "*.pyc", "*.pyo", "*.egg-info")(directory, names))
    path = Path(directory)
    if path.name == "assets" and path.parent.name == "砖了个砖提示":
        # These two images are test fixtures, not runtime recognition templates.
        ignored.update({"reference.png", "reference_hose.png"} & set(names))
    return ignored


def runtime_ignore(directory, names):
    ignored = {name for name in names if name == "__pycache__" or name.endswith((".pyc", ".pyo", ".egg-info"))}
    path = Path(directory)
    if path.name == "Lib" and path.parent.name == "python":
        # CPython's regression suite includes certificate fixtures, not runtime data.
        ignored.add("test")
    elif path.name == "PySide6":
        ignored.update(name for name in names if name in {
            "qml", "include", "typesystems", "glue", "scripts", "resources", "translations",
            "metatypes", "pyside6qml.abi3.dll", "opengl32sw.dll",
        } or name.endswith((".exe", ".lib")))
        for name in names:
            if name.startswith("Qt6") and name.endswith(".dll") and name[3:-4] not in QT_MODULES:
                ignored.add(name)
            elif name.startswith("Qt") and name.endswith((".pyd", ".pyi")) and Path(name).stem[2:] not in QT_MODULES:
                ignored.add(name)
    elif path.name == "plugins" and path.parent.name == "PySide6":
        ignored.update(set(names) - {"platforms", "styles", "imageformats", "iconengines", "tls", "networkinformation"})
    elif path.name == "imageformats" and path.parent.parent.name == "PySide6":
        ignored.add("qpdf.dll")
    elif path.name == "Scripts" and path.parent.name == "python":
        # pip-generated launchers embed the build machine's absolute interpreter path.
        ignored.update(name for name in names if name.endswith(".exe"))
    elif path.name == "cv2":
        # The host and bundled skill process still images, not video codecs.
        ignored.update(name for name in names if name.startswith("opencv_videoio_ffmpeg") and name.endswith(".dll"))
    return ignored


def task_directory(root, task_id):
    if not re.fullmatch(r"[^\W_][\w-]*", task_id):
        raise ValueError(f"Invalid task id: {task_id!r}")
    tasks_root = (Path(root) / "tasks").resolve()
    directory = (tasks_root / task_id).resolve()
    if not directory.is_relative_to(tasks_root):
        raise ValueError(f"Task directory escapes tasks root: {task_id}")
    if not (directory / "task.py").is_file():
        raise FileNotFoundError(directory / "task.py")
    if not (directory / "skill.json").is_file():
        raise FileNotFoundError(directory / "skill.json")
    return directory


def fingerprint_tree(directory):
    """Hash paths and contents; interpreter-generated bytecode is not release input."""
    digest = hashlib.sha256()
    directory = Path(directory).resolve()
    if not directory.is_dir():
        raise FileNotFoundError(directory)
    for current, dirs, files in os.walk(directory):
        ignored = runtime_ignore(current, dirs + files)
        dirs[:] = sorted(name for name in dirs if name not in ignored)
        for name in sorted(files):
            if name in ignored:
                continue
            path = Path(current) / name
            if not path.resolve().is_relative_to(directory):
                raise ValueError(f"File escapes package directory: {path}")
            digest.update(path.relative_to(directory).as_posix().encode("utf-8") + b"\0")
            with path.open("rb") as stream:
                digest.update(hashlib.file_digest(stream, "sha256").digest())
    return digest.hexdigest()


def environment_info(runtime):
    runtime = Path(runtime).resolve()
    environment = os.environ.copy()
    environment.pop("PYTHONHOME", None)
    environment.pop("PYTHONPATH", None)
    environment["PATH"] = str(Path(os.environ["SystemRoot"]) / "System32")
    result = subprocess.run(
        [str(runtime / "python.exe"), "-I", "-X", "utf8", "-c",
         "import json, platform, sys, cv2, numpy, PIL, windows_capture, huanzhizhi; "
         "from PySide6 import QtCore, QtGui, QtWidgets; "
         "from importlib.metadata import distributions; from pathlib import Path; "
         "root = Path(sys.executable).resolve().parent; "
         "assert Path(sys.prefix).resolve() == root; "
         "assert all(Path(m.__file__).resolve().is_relative_to(root) "
         "for m in (cv2, numpy, PIL, windows_capture, QtCore)); "
         "assert Path(huanzhizhi.__file__).resolve().is_relative_to(root.parent / 'src'); "
         "print(json.dumps({'python': platform.python_version(), 'architecture': platform.machine(), "
         "'dependencies': {d.metadata['Name']: d.version for d in distributions()}}))"],
        cwd=runtime, env=environment, capture_output=True, text=True, encoding="utf-8",
        timeout=30, creationflags=subprocess.CREATE_NO_WINDOW,
    )
    if result.returncode:
        raise RuntimeError(f"项目 Python 依赖验证失败：{result.stderr}")
    return json.loads(result.stdout)


def check_environment(bundle, project_root):
    """A skill update may only reuse the exact host code and shared Python libraries."""
    bundle, project_root = Path(bundle).resolve(), Path(project_root).resolve()
    manifest = json.loads((bundle / "build-info.json").read_text(encoding="utf-8"))
    if manifest.get("format") != FORMAT:
        raise ValueError("发行包不是统一 Python 结构，请完整重新打包")
    for directory, field in (("python", "runtime_sha256"), ("src", "host_sha256")):
        expected = manifest.get(field)
        if (fingerprint_tree(bundle / directory) != expected
                or fingerprint_tree(project_root / directory) != expected):
            raise ValueError(f"共享 {directory} 与发行包不兼容，请完整重新打包；不会覆盖公共文件")
    return manifest
